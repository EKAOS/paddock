-- ===== Échange flash : une heure par jour (entre 12 h et 23 h, la même pour tous), 3 doublons contre 1 carte de la rareté au-dessus, 3 fois par jour =====
create or replace function public._flash_hour(d date) returns int language sql immutable as $$ select 12 + (((d - date '2026-01-01') * 7 + 3) % 11) $$;
create or replace function public.flash_trade(r text) returns jsonb language plpgsql security definer set search_path = public as $$
declare u uuid := _uid(); t timestamp := now() at time zone 'Europe/Paris'; d date := t::date; nxt text; done int; need int := 3; rec record; take int; c int; isnew boolean;
begin
  if u is null then raise exception 'Connectez-vous pour échanger.'; end if;
  if extract(hour from t)::int <> _flash_hour(d) then raise exception 'L''échange flash n''est pas ouvert en ce moment.'; end if;
  nxt := case r when 'C' then 'PC' when 'PC' then 'R' when 'R' then 'SR' when 'SR' then 'UR' when 'UR' then 'L' end;
  if nxt is null then raise exception 'Cette rareté ne peut pas être échangée.'; end if;
  select n into done from flash_trades where user_id = u and day = d;
  if coalesce(done, 0) >= 3 then raise exception 'Vous avez déjà fait vos 3 échanges flash aujourd''hui.'; end if;
  -- on prend les doublons les plus nombreux d'abord ; les brillantes et le dernier exemplaire ne sont jamais utilisés
  for rec in select i.card_id, i.n - 1 - coalesce((to_jsonb(i) ->> 'holo')::int, 0) as spare
             from inventory i join cards k on k.id = i.card_id
             where i.user_id = u and k.rarity = r and i.n - 1 - coalesce((to_jsonb(i) ->> 'holo')::int, 0) > 0
             order by 2 desc loop
    exit when need = 0;
    take := least(need, rec.spare);
    update inventory set n = n - take where user_id = u and card_id = rec.card_id;
    need := need - take;
  end loop;
  if need > 0 then raise exception 'Il faut 3 doublons de cette rareté.'; end if;
  if random() < 0.5 then select id into c from cards where rarity = nxt and id >= 4327 order by random() limit 1; end if;
  if c is null then select id into c from cards where rarity = nxt order by random() limit 1; end if;
  isnew := _give(u, c, false);
  insert into flash_trades values (u, d, 1) on conflict (user_id, day) do update set n = flash_trades.n + 1;
  return jsonb_build_object('id', c, 'new', isnew, 'left', 2 - coalesce(done, 0));
end $$;
revoke all on function public._flash_hour(date) from public, anon, authenticated;
revoke all on function public.flash_trade(text) from public, anon;
grant execute on function public.flash_trade(text) to authenticated;

-- ===== Prestige : 20 écussons au lieu de 5 (les écussons VI à XX restent secrets dans le jeu tant qu'on ne les a pas) =====
create or replace function public.do_prestige() returns jsonb language plpgsql security definer set search_path = public as $$
declare u uuid := _uid(); p profiles; c int;
begin
  select * into p from profiles where id = u for update;
  if p.prestige >= 20 then raise exception 'Vous avez déjà le dernier écusson de prestige.'; end if;
  if _lvl(p.xp) < 30 then raise exception 'Le prestige se débloque au niveau 30.'; end if;
  update profiles set xp = 0, prestige = prestige + 1 where id = u;
  update wallets set packs = packs + 10 where user_id = u;
  select id into c from cards where rarity = 'L' order by random() limit 1;
  perform _give_signed(u, c);
  perform _notify(u, 'Prestige ' || (p.prestige + 1) || ' : nouvel écusson ! 10 paquets et une légendaire signée vous attendent.');
  return jsonb_build_object('prestige', p.prestige + 1, 'card', c);
end $$;


-- ===== Succès Série 02 : 9 succès, vérifiés sur l'inventaire, récompense en pistons =====
create or replace function public.claim_s2ach(k text) returns jsonb language plpgsql security definer set search_path = public as $$
declare u uuid := _uid(); need int; prize int; cur int;
  fr text[] := '{Renault,Peugeot,Citroën,Alpine,DS,Simca,Simca-Talbot,Simca-Chrysler,Matra,Matra-Simca,Talbot,Talbot-Lago,Venturi,Bugatti,Delahaye,Delage,Panhard,Hispano-Suiza,Ligier,"Facel Vega",Rondeau,Pescarolo,Courage,Mobilize,Genty}';
begin
  if u is null then raise exception 'Connectez-vous pour récupérer ce succès.'; end if;
  select x.need, x.prize into need, prize from (values ('s2_espace',3,50),('s2_p34',1,25),('s2_tyrrell',5,50),('s2_2020',10,50),('s2_old',5,50),('s2_fr',20,50),('s2_ferrari',10,75),('s2_brands',50,75),('s2_leg',5,100)) as x(k, need, prize) where x.k = claim_s2ach.k;
  if need is null then raise exception 'Succès inconnu.'; end if;
  select case claim_s2ach.k
      when 's2_brands' then count(distinct c.brand)
      else count(*) filter (where case claim_s2ach.k
        when 's2_espace' then c.id in (4329, 4332, 4335)
        when 's2_p34' then c.id = 4339
        when 's2_tyrrell' then c.brand = 'Tyrrell'
        when 's2_2020' then c.y1 >= 2020
        when 's2_old' then c.y1 < 1950
        when 's2_fr' then c.brand = any(fr)
        when 's2_ferrari' then c.brand = 'Ferrari'
        when 's2_leg' then c.rarity = 'L' end) end
    into cur from inventory i join cards c on c.id = i.card_id where i.user_id = u and i.n > 0 and i.card_id >= 4327;
  if cur < need then raise exception 'Succès pas encore atteint (% / %).', cur, need; end if;
  insert into s2_ach(user_id, k) values (u, claim_s2ach.k) on conflict do nothing;
  if not found then raise exception 'Succès déjà récupéré.'; end if;
  update wallets set coins = coins + prize where user_id = u;
  return jsonb_build_object('ach', (select jsonb_agg(a.k) from s2_ach a where a.user_id = u), 'coins', (select coins from wallets where user_id = u));
end $$;

-- ===== Département affiché sur la plaque d'immatriculation =====
create or replace function public.set_plate_dep(d text) returns text language plpgsql security definer set search_path = public as $$
declare u uuid := _uid(); v text := nullif(upper(trim(coalesce(d, ''))), '');
begin
  if u is null then raise exception 'Connectez-vous.'; end if;
  if v is not null and v !~ '^(0[1-9]|[1-8][0-9]|9[0-5]|2A|2B|97[1-46])$' then raise exception 'Département inconnu.'; end if;
  update profiles set plate_dep = v where id = u;
  return v;
end $$;
create or replace function public.get_plate_dep(name text) returns text language sql stable security definer set search_path = public as $$
  select plate_dep from profiles where lower(username) = lower(name) and not banned limit 1;
$$;
